let currentLang = 'it';
let activeIndex = 17;
let isTimeFrozen = false;
let scene, camera, renderer, networkGroup, nodesMesh, linesMesh, positions, colors, nodeCount = 180;
let isDragging = false;
let previousPointer = { x: 0, y: 0 };
let pointerSpeed = 0;
let lastPointerPos = { x: 0, y: 0 };
let audioCtx, osc, gainNode;

function setLanguage(lang) {
  currentLang = lang;
  document.getElementById('lang-it').classList.toggle('active-lang', lang === 'it');
  document.getElementById('lang-en').classList.toggle('active-lang', lang === 'en');

  const dict = i18n[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.innerText = dict[key];
  });

  const audioToggle = document.getElementById('audio-toggle');
  if (audioCtx && audioCtx.state === 'running') {
    audioToggle.innerText = dict.audioActive;
  } else {
    audioToggle.innerText = dict.audioMute;
  }

  renderIndexList();
  updateSectionDataUI(activeIndex);
}

function renderIndexList() {
  const listEl = document.getElementById('index-list');
  listEl.innerHTML = '';
  const sections = i18n[currentLang].sections;

  sections.forEach((sec, idx) => {
    const li = document.createElement('li');
    li.className = `index-item ${idx === activeIndex ? 'active' : ''}`;
    li.innerHTML = `<span class="item-num">${sec.num}</span><span class="item-name">${sec.name}</span>`;
    li.addEventListener('click', () => {
      if (!isTimeFrozen) selectSection(idx);
    });
    listEl.appendChild(li);
  });
}

function updateSectionDataUI(idx) {
  const data = i18n[currentLang].sections[idx];
  const dict = i18n[currentLang];
  
  document.getElementById('section-kicker').innerText = `${dict.nowPrefix} ${data.num}`;
  document.getElementById('section-title').innerText = data.name;
  document.getElementById('section-desc').innerText = data.desc;
}

function selectSection(idx) {
  if (idx === activeIndex || isTimeFrozen) return;
  activeIndex = idx;

  document.querySelectorAll('.index-item').forEach((item, i) => {
    item.classList.toggle('active', i === idx);
    if (i === idx) item.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  });

  gsap.to(['#section-title', '#section-desc'], {
    opacity: 0,
    y: -6,
    duration: 0.15,
    onComplete: () => {
      updateSectionDataUI(activeIndex);
      gsap.to(['#section-title', '#section-desc'], { opacity: 1, y: 0, duration: 0.25 });
    }
  });

  if (osc && audioCtx) {
    const freq = 120 + idx * 18;
    osc.frequency.setValueAtTime(freq, audioCtx.currentTime);
    document.getElementById('freq-val').innerText = `${Math.round(freq)} HZ`;
  }
}

function init3D() {
  const canvas = document.getElementById('webgl-canvas');
  scene = new THREE.Scene();

  // Controllo per identificare la modalità desktop da quella mobile
  const isDesktop = window.matchMedia('(min-width: 1025px) and (pointer: fine)').matches;
  const width = isDesktop ? window.innerWidth : (canvas.clientWidth || window.innerWidth);
  const height = isDesktop ? window.innerHeight : (canvas.clientHeight || window.innerHeight);

  camera = new THREE.PerspectiveCamera(40, width / height, 0.1, 1000);
  camera.position.set(0, 0, 7.5);

  renderer = new THREE.WebGLRenderer({ canvas, antialias: true, alpha: true });
  renderer.setClearColor(0x000000, 0);
  renderer.setSize(width, height, false);
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));

  networkGroup = new THREE.Group();
  positions = [];
  colors = [];

  const baseColor = new THREE.Color(0xdddddd);
  const limeColor = new THREE.Color(0xd7ff3f);

  for (let i = 0; i < nodeCount; i++) {
    const u = Math.random();
    const v = Math.random();
    const theta = u * 2.0 * Math.PI;
    const phi = Math.acos(2.0 * v - 1.0);
    const r = 2.0 + (Math.random() - 0.5) * 0.4;

    const x = r * Math.sin(phi) * Math.cos(theta);
    const y = r * Math.sin(phi) * Math.sin(theta);
    const z = r * Math.cos(phi);

    positions.push(x, y, z);

    const mixColor = baseColor.clone().lerp(limeColor, Math.random() * 0.45);
    colors.push(mixColor.r, mixColor.g, mixColor.b);
  }

  const nodesGeo = new THREE.BufferGeometry();
  nodesGeo.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  nodesGeo.setAttribute('color', new THREE.Float32BufferAttribute(colors, 3));

  const nodesMat = new THREE.PointsMaterial({
    size: 0.06,
    vertexColors: true,
    transparent: true,
    opacity: 0.95
  });

  nodesMesh = new THREE.Points(nodesGeo, nodesMat);
  networkGroup.add(nodesMesh);

  const linePositions = [];
  const lineColors = [];

  for (let i = 0; i < nodeCount; i++) {
    for (let j = i + 1; j < nodeCount; j++) {
      const dx = positions[i * 3] - positions[j * 3];
      const dy = positions[i * 3 + 1] - positions[j * 3 + 1];
      const dz = positions[i * 3 + 2] - positions[j * 3 + 2];
      const dist = Math.sqrt(dx * dx + dy * dy + dz * dz);

      if (dist < 0.85) {
        linePositions.push(positions[i * 3], positions[i * 3 + 1], positions[i * 3 + 2]);
        linePositions.push(positions[j * 3], positions[j * 3 + 1], positions[j * 3 + 2]);

        const c1 = new THREE.Color(colors[i * 3], colors[i * 3 + 1], colors[i * 3 + 2]);
        const c2 = new THREE.Color(colors[j * 3], colors[j * 3 + 1], colors[j * 3 + 2]);

        lineColors.push(c1.r, c1.g, c1.b);
        lineColors.push(c2.r, c2.g, c2.b);
      }
    }
  }

  const linesGeo = new THREE.BufferGeometry();
  linesGeo.setAttribute('position', new THREE.Float32BufferAttribute(linePositions, 3));
  linesGeo.setAttribute('color', new THREE.Float32BufferAttribute(lineColors, 3));

  const linesMat = new THREE.LineBasicMaterial({
    vertexColors: true,
    transparent: true,
    opacity: 0.35
  });

  linesMesh = new THREE.LineSegments(linesGeo, linesMat);
  networkGroup.add(linesMesh);

  networkGroup.rotation.y = (17 / 24) * Math.PI * 2;
  scene.add(networkGroup);

  window.addEventListener('resize', onResize);
  window.addEventListener('orientationchange', () => setTimeout(onResize, 200));
}

function onResize() {
  const canvas = document.getElementById('webgl-canvas');
  if (!canvas) return;
  
  const isDesktop = window.matchMedia('(min-width: 1025px) and (pointer: fine)').matches;
  const width = isDesktop ? window.innerWidth : (canvas.clientWidth || window.innerWidth);
  const height = isDesktop ? window.innerHeight : (canvas.clientHeight || window.innerHeight);

  camera.aspect = width / height;
  camera.updateProjectionMatrix();
  renderer.setSize(width, height, false);
}

function initInteractions() {
  const cursor = document.getElementById('cursor');

  function handlePointerMove(clientX, clientY) {
    if (cursor) {
      cursor.style.left = `${clientX}px`;
      cursor.style.top = `${clientY}px`;
    }

    const dx = clientX - lastPointerPos.x;
    const dy = clientY - lastPointerPos.y;
    pointerSpeed = Math.sqrt(dx * dx + dy * dy) * 0.05;
    lastPointerPos = { x: clientX, y: clientY };

    const speedEl = document.getElementById('speed-val');
    if (speedEl) speedEl.innerText = `${pointerSpeed.toFixed(2)} M/S`;
    updateSparkline(pointerSpeed);

    if (isDragging && networkGroup && !isTimeFrozen) {
      const deltaX = clientX - previousPointer.x;
      const deltaY = clientY - previousPointer.y;

      networkGroup.rotation.y += deltaX * 0.008;
      networkGroup.rotation.x += deltaY * 0.008;

      let normalizedAngle = (networkGroup.rotation.y % (Math.PI * 2) + Math.PI * 2) % (Math.PI * 2);
      let calculatedIndex = Math.floor((normalizedAngle / (Math.PI * 2)) * 24);

      selectSection(calculatedIndex);
    }
    previousPointer = { x: clientX, y: clientY };
  }

  // Pointer event globale per il tracking sia su desktop che su schermi touch
  window.addEventListener('pointermove', (e) => {
    handlePointerMove(e.clientX, e.clientY);
  });

  window.addEventListener('pointerdown', (e) => {
    // Attiva il drag ovunque su Desktop, oppure se si tocca direttamente la palla nei dispositivi portatili
    const isDesktop = window.matchMedia('(min-width: 1025px) and (pointer: fine)').matches;
    if (isDesktop || e.target.id === 'webgl-canvas') {
      isDragging = true;
      previousPointer = { x: e.clientX, y: e.clientY };
      lastPointerPos = { x: e.clientX, y: e.clientY };
    }
  });

  const stopDragging = () => { isDragging = false; };
  window.addEventListener('pointerup', stopDragging);
  window.addEventListener('pointercancel', stopDragging);

  document.querySelectorAll('a, button, .menu-item, .index-item, .lang-switch, .brand, .card-link').forEach(el => {
    el.addEventListener('mouseenter', () => cursor && cursor.classList.add('hovered'));
    el.addEventListener('mouseleave', () => cursor && cursor.classList.remove('hovered'));
  });

  document.getElementById('audio-toggle').addEventListener('click', toggleAudio);
  document.getElementById('lang-btn').addEventListener('click', () => setLanguage(currentLang === 'it' ? 'en' : 'it'));
  
  document.getElementById('btn-logo').addEventListener('click', () => {
    if (isTimeFrozen) return;
    gsap.to(networkGroup.rotation, { x: 0, y: 0, duration: 1 });
    selectSection(0);
  });

  document.getElementById('btn-atlas').addEventListener('click', () => {
    if (isTimeFrozen) return;
    const targetY = (17 / 24) * Math.PI * 2;
    gsap.to(networkGroup.rotation, { x: 0, y: targetY, duration: 1 });
    selectSection(17);
  });

  document.getElementById('btn-useless').addEventListener('click', triggerUselessPulse);
  document.getElementById('section-link').addEventListener('click', (e) => {
    e.preventDefault();
    openModal();
  });
  document.getElementById('modal-close').addEventListener('click', closeModal);
  document.getElementById('modal-hour').addEventListener('click', (e) => {
    if (e.target.id === 'modal-hour') closeModal();
  });
}

function triggerUselessPulse() {
  gsap.to(networkGroup.scale, {
    x: 1.3, y: 1.3, z: 1.3,
    duration: 0.2,
    yoyo: true,
    repeat: 1,
    ease: "power2.out"
  });

  if (osc && audioCtx) {
    osc.frequency.setValueAtTime(440, audioCtx.currentTime);
    setTimeout(() => {
      osc.frequency.setValueAtTime(120 + activeIndex * 18, audioCtx.currentTime);
    }, 300);
  }
}

function openModal() {
  isTimeFrozen = true;
  const modal = document.getElementById('modal-hour');
  const dict = i18n[currentLang];
  const sec = dict.sections[activeIndex];

  document.getElementById('modal-kicker').innerText = `${dict.nowPrefix} ${sec.num}`;
  document.getElementById('modal-title').innerText = sec.name;
  document.getElementById('modal-body').innerText = `${sec.desc}\n\n${dict.modalDetails}`;

  modal.classList.add('open');
}

function closeModal() {
  isTimeFrozen = false;
  document.getElementById('modal-hour').classList.remove('open');
}

const sparklineVals = new Array(12).fill(2);
function updateSparkline(val) {
  sparklineVals.shift();
  sparklineVals.push(Math.min(Math.max(val * 5, 2), 16));

  const container = document.getElementById('sparkline');
  if (container) {
    container.innerHTML = '';
    sparklineVals.forEach(v => {
      const bar = document.createElement('div');
      bar.className = 'spark-bar';
      bar.style.height = `${v}px`;
      container.appendChild(bar);
    });
  }
}

function toggleAudio() {
  const dict = i18n[currentLang];
  const audioToggle = document.getElementById('audio-toggle');

  if (!audioCtx) {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    osc = audioCtx.createOscillator();
    gainNode = audioCtx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(120 + activeIndex * 18, audioCtx.currentTime);
    gainNode.gain.setValueAtTime(0.02, audioCtx.currentTime);

    osc.connect(gainNode);
    gainNode.connect(audioCtx.destination);
    osc.start();

    audioToggle.innerText = dict.audioActive;
  } else if (audioCtx.state === 'suspended') {
    audioCtx.resume();
    audioToggle.innerText = dict.audioActive;
  } else {
    audioCtx.suspend();
    audioToggle.innerText = dict.audioMute;
  }
}

function updateClock() {
  const now = new Date();
  const clockEl = document.getElementById('clock-val');
  if (clockEl) clockEl.innerText = now.toTimeString().split(' ')[0];
}

function animate() {
  requestAnimationFrame(animate);

  if (!isDragging && networkGroup && !isTimeFrozen) {
    networkGroup.rotation.y += 0.002;

    let normalizedAngle = (networkGroup.rotation.y % (Math.PI * 2) + Math.PI * 2) % (Math.PI * 2);
    let calculatedIndex = Math.floor((normalizedAngle / (Math.PI * 2)) * 24);
    selectSection(calculatedIndex);
  }

  renderer.render(scene, camera);
}

window.addEventListener('DOMContentLoaded', () => {
  init3D();
  setLanguage('it');
  initInteractions();
  animate();
  setInterval(updateClock, 1000);
  updateClock();
});
